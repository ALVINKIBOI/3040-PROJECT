    private void configureUserInterface() {

        lblWelcome.setText(
                "Welcome back, " + currentUser.fullName()
        );

        lblRole.setText(currentUser.role());

        boolean isAdmin
                = "ADMIN".equals(currentUser.role());

        // Admin-specific navigation
        btnManageUsers.setVisible(isAdmin);
        btnReviewClaims.setVisible(isAdmin);
        btnManageCatalog.setVisible(isAdmin);

        // General-user-specific navigation
        btnMyReports.setVisible(!isAdmin);
        btnMyClaims.setVisible(!isAdmin);
        btnReportLost.setVisible(!isAdmin);
        btnQuickLost.setVisible(!isAdmin);

        // Both roles can access these actions
        btnReportFound.setVisible(true);
        btnBrowseItems.setVisible(true);
        btnNotifications.setVisible(true);
        btnSuggestedMatches.setVisible(true);

        if (isAdmin) {

            lblStatTitle1.setText("Total Reports");
            lblStatTitle2.setText("Open Reports");
            lblStatTitle3.setText("Pending Claims");
            lblStatTitle4.setText("Returned Items");

        } else {

            lblStatTitle1.setText("My Reports");
            lblStatTitle2.setText("Open Reports");
            lblStatTitle3.setText("Suggested Matches");
            lblStatTitle4.setText("Pending Claims");
        }

        pnlSideBar.revalidate();
        pnlSideBar.repaint();
    }

    private void loadDashboardStatistics() {

        if (currentUser == null) {
            return;
        }

        btnRefresh.setEnabled(false);

        lblStatValue1.setText("...");
        lblStatValue2.setText("...");
        lblStatValue3.setText("...");
        lblStatValue4.setText("...");

        javax.swing.SwingWorker<Models.DashboardStats, Void> worker
                = new javax.swing.SwingWorker<>() {

            @Override
            protected Models.DashboardStats doInBackground()
                    throws Exception {

                return dashboardService.loadStats(
                        currentUser
                );
            }

            @Override
            protected void done() {

                btnRefresh.setEnabled(true);

                try {

                    Models.DashboardStats stats = get();

                    lblStatValue1.setText(
                            String.valueOf(stats.first())
                    );

                    lblStatValue2.setText(
                            String.valueOf(stats.second())
                    );

                    lblStatValue3.setText(
                            String.valueOf(stats.third())
                    );

                    lblStatValue4.setText(
                            String.valueOf(stats.fourth())
                    );

                } catch (InterruptedException ex) {

                    Thread.currentThread().interrupt();

                    showStatisticsError();

                } catch (java.util.concurrent.ExecutionException ex) {

                    ex.getCause().printStackTrace();
                    showStatisticsError();
                }
            }
        };

        worker.execute();
    }

    private void showStatisticsError() {

        lblStatValue1.setText("—");
        lblStatValue2.setText("—");
        lblStatValue3.setText("—");
        lblStatValue4.setText("—");

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not load dashboard statistics.",
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

