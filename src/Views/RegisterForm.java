    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:

        if (!validateRegistration()) {
            return;
        }
        String role
                = (String) cmbRole.getSelectedItem();

        String programme = null;
        Integer yearOfStudy = null;
        String department = null;

        if ("Student".equals(role)) {

            programme
                    = txtProgramme.getText().trim();

            yearOfStudy = Integer.valueOf(
                    cmbYearOfStudy
                            .getSelectedItem()
                            .toString()
            );

        } else if ("Staff".equals(role)) {

            department
                    = txtDepartment.getText().trim();
        }

        RegistrationData data
                = new RegistrationData(
                        txtFullName.getText().trim(),
                        txtUsiuId.getText().trim(),
                        txtEmail.getText().trim(),
                        txtPhone.getText().trim(),
                        role,
                        programme,
                        yearOfStudy,
                        department
                );

        char[] password
                = txtPassword.getPassword();

        btnRegister.setEnabled(false);
        lblError.setText("Creating account...");

        SwingWorker<Void, Void> worker
                = new SwingWorker<>() {

            @Override
            protected Void doInBackground()
                    throws Exception {

                try {
                    authController.register(
                            data, password
                    );
                    return null;

                } finally {
                    Arrays.fill(password, '\0');
                }
            }

            @Override
            protected void done() {

                btnRegister.setEnabled(true);

                try {
                    get();

                    lblError.setText(" ");

                    txtPassword.setText("");
                    txtConfirmPassword.setText("");

                    JOptionPane.showMessageDialog(
                            RegisterForm.this,
                            "Account created successfully!"
                            + "\nYou can now sign in.",
                            "Registration Successful",
                            JOptionPane.INFORMATION_MESSAGE
                    );

                    LoginFrame login = new LoginFrame();
                    login.setLocationRelativeTo(null);
                    login.setVisible(true);

                    dispose();

                } catch (InterruptedException ex) {
                    Thread.currentThread().interrupt();

                    lblError.setText(
                            "Registration was interrupted."
                    );

                } catch (ExecutionException ex) {

                    Throwable cause = ex.getCause();

                    if (cause instanceof IllegalArgumentException) {

                        lblError.setText(
                                cause.getMessage()
                        );

                    } else {
                        lblError.setText(
                                "Unable to register. "
                                + "Please try again."
                        );

                    }
                }
            }
        };

        worker.execute();
    }//GEN-LAST:event_btnRegisterActionPerformed

