    private boolean validateRegistration() {

        String fullName = txtFullName.getText().trim();
        String usiuId = txtUsiuId.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();

        String role = (String) cmbRole.getSelectedItem();

        lblError.setText(" ");

        if (fullName.isEmpty()) {
            return showError(
                    "Please enter your full name.",
                    txtFullName
            );
        }

        if (usiuId.isEmpty()) {
            return showError(
                    "Please enter your USIU ID.",
                    txtUsiuId
            );
        }

        if (!email.matches(
                "(?i)^[A-Z0-9._%+-]+@usiu\\.ac\\.ke$")) {
            return showError(
                    "Enter a valid USIU email.",
                    txtEmail
            );
        }

        if (phone.isEmpty()) {
            return showError(
                    "Please enter your phone number.",
                    txtPhone
            );
        }

        if ("Student".equals(role)) {

            if (txtProgramme.getText().trim().isEmpty()) {
                return showError(
                        "Please enter your programme.",
                        txtProgramme
                );
            }

            if (cmbYearOfStudy.getSelectedIndex() <= 0) {
                return showError(
                        "Please select your year of study.",
                        cmbYearOfStudy
                );
            }

        } else if ("Staff".equals(role)) {

            if (txtDepartment.getText().trim().isEmpty()) {
                return showError(
                        "Please enter your department.",
                        txtDepartment
                );
            }

        } else {
            lblError.setText(
                    "Please select an account type."
            );
            return false;
        }

        char[] password = txtPassword.getPassword();
        char[] confirm = txtConfirmPassword.getPassword();

        try {
            if (password.length < 8) {
                return showError(
                        "Password must contain at least 8 characters.",
                        txtPassword
                );
            }

            if (!Arrays.equals(password, confirm)) {
                return showError(
                        "Passwords do not match.",
                        txtConfirmPassword
                );
            }
        } finally {
            Arrays.fill(password, '\0');
            Arrays.fill(confirm, '\0');
        }

        return true;
    }

    private boolean showError(
            String message,
            java.awt.Component component) {

        lblError.setText(message);
        component.requestFocusInWindow();
        return false;
    }

