    private void updateRoleFields() {

        String selectedRole
                = (String) cmbRole.getSelectedItem();

        if (selectedRole == null) {
            return;
        }

        CardLayout layout
                = (CardLayout) pnlRoleFields.getLayout();

        if (selectedRole.equals("Student")) {
            layout.show(pnlRoleFields, "STUDENT");

        } else if (selectedRole.equals("Staff")) {
            layout.show(pnlRoleFields, "STAFF");
        }

        pnlRoleFields.revalidate();
        pnlRoleFields.repaint();

    }

