    private void loadClaimItem() {

        lblClaimError.setText("Loading item details...");

        SwingWorker<ClaimItemDetails, Void> worker
                = new SwingWorker<>() {

            @Override
            protected ClaimItemDetails doInBackground()
                    throws Exception {

                return controller.getClaimItem(
                        foundItemId
                );
            }

            @Override
            protected void done() {

                try {
                    ClaimItemDetails item = get();

                    if (item == null) {
                        lblClaimError.setText(
                                "This found item is no longer available."
                        );
                        return;
                    }

                    lblItemTitle.setText(item.title());
                    lblItemStatus.setText(
                            "Status: " + item.status()
                    );

                    lblVerificationQuestion.setText(
                            "<html>"
                            + escapeHtml(item.verificationQuestion())
                            + "</html>"
                    );

                    btnSubmitClaim.setEnabled(true);
                    lblClaimError.setText(" ");

                } catch (Exception ex) {
                    ex.printStackTrace();

                    lblClaimError.setText(
                            "Unable to load found item details."
                    );
                }
            }
        };

        worker.execute();
    }

    private String escapeHtml(String text) {

        if (text == null) {
            return "";
        }

        return text.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;");
    }

    private void returnToDashboard() {

        if (navigationCompleted) {
            return;
        }

        navigationCompleted = true;

        if (onReturnToDashboard != null) {
            onReturnToDashboard.run();
        } else if (onReturnToBrowse != null) {
            onReturnToBrowse.run();
        }

        dispose();
    }

    private void returnToBrowse() {

        if (navigationCompleted) {
            return;
        }

        navigationCompleted = true;

        if (onReturnToBrowse != null) {
            onReturnToBrowse.run();
        }

        dispose();
    }

