    private void btnSubmitClaimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitClaimActionPerformed
        // TODO add your handling code here:
        if (currentUser == null) {
            lblClaimError.setText("Please log in first.");
            return;
        }

        char[] answer
                = txtVerificationAnswer.getPassword();

        String proof
                = txtProofOfOwnership.getText().trim();

        if (answer.length == 0 || proof.isEmpty()) {

            Arrays.fill(answer, '\0');

            lblClaimError.setText(
                    "Verification answer and proof are required."
            );
            return;
        }

        btnSubmitClaim.setEnabled(false);
        lblClaimError.setText("Submitting claim...");

        SwingWorker<Integer, Void> worker
                = new SwingWorker<>() {

            @Override
            protected Integer doInBackground()
                    throws Exception {

                return controller.submitClaim(
                        currentUser.userId(),
                        foundItemId,
                        answer,
                        proof
                );
            }

            @Override
            protected void done() {

                btnSubmitClaim.setEnabled(true);
                txtVerificationAnswer.setText("");

                try {
                    int claimId = get();

                    lblClaimError.setText(" ");

                    JOptionPane.showMessageDialog(
                            ClaimItem.this,
                            "Claim submitted successfully!\n"
                            + "Claim ID: " + claimId
                            + "\nStatus: PENDING"
                            + "\nAwait administrator review.",
                            "Claim Submitted",
                            JOptionPane.INFORMATION_MESSAGE
                    );

                    returnToBrowse();

                } catch (Exception ex) {

                    Throwable cause
                            = ex instanceof java.util.concurrent.ExecutionException
                            && ex.getCause() != null
                            ? ex.getCause()
                            : ex;

                    cause.printStackTrace();

                    lblClaimError.setText(
                            cause.getMessage() == null
                            ? "Unable to submit claim."
                            : cause.getMessage()
                    );

                    JOptionPane.showMessageDialog(
                            ClaimItem.this,
                            lblClaimError.getText(),
                            "Claim Submission Failed",
                            JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        };

        worker.execute();
    }//GEN-LAST:event_btnSubmitClaimActionPerformed

