    private void btnSaveChangesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveChangesActionPerformed
        // TODO add your handling code here:

        if (report == null || currentUser == null) {
            return;
        }

        try {
            CatalogOption category
                    = (CatalogOption) cmbEditCategory.getSelectedItem();

            CatalogOption location
                    = (CatalogOption) cmbEditLocation.getSelectedItem();

            if (category == null || location == null) {
                throw new IllegalArgumentException(
                        "Select category and location."
                );
            }

            String title
                    = txtEditTitle.getText().trim();

            String description
                    = txtDescription.getText().trim();

            LocalDate date = LocalDate.parse(
                    txtEditDate.getText().trim()
            );

            BigDecimal reward = null;
            String features = null;
            String storage = null;

            if ("LOST".equals(report.itemType())) {

                features = txtEditFeatures.getText().trim();

                String rewardText
                        = txtEditReward.getText().trim();

                if (!rewardText.isEmpty()) {
                    reward = new BigDecimal(rewardText);
                }

            } else {

                storage = txtStorage.getText().trim();
            }

            final BigDecimal finalReward = reward;
            final String finalFeatures = features;
            final String finalStorage = storage;

            btnSaveChanges.setEnabled(false);
            lblEditError.setText("Saving changes...");

            SwingWorker<Void, Void> worker
                    = new SwingWorker<>() {

                @Override
                protected Void doInBackground()
                        throws Exception {

                    controller.updateReport(
                            reportId,
                            currentUser.userId(),
                            title,
                            description,
                            category.id(),
                            location.id(),
                            date,
                            finalFeatures,
                            finalReward,
                            finalStorage
                    );

                    return null;
                }

                @Override
                protected void done() {

                    btnSaveChanges.setEnabled(true);

                    try {
                        get();

                        JOptionPane.showMessageDialog(
                                EditReport.this,
                                "Report updated successfully!"
                        );

                        if (onSaved != null) {
                            onSaved.run();
                        }

                        dispose();

                    } catch (Exception ex) {

                        Throwable cause
                                = ex instanceof java.util.concurrent.ExecutionException
                                && ex.getCause() != null
                                ? ex.getCause()
                                : ex;

                        lblEditError.setText(
                                cause.getMessage()
                        );
                    }
                }
            };

            worker.execute();

        } catch (Exception ex) {

            lblEditError.setText(
                    "Check the date, reward and required fields."
            );
        }
    }//GEN-LAST:event_btnSaveChangesActionPerformed

