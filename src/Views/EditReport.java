    private void loadReport() {

        btnSaveChanges.setEnabled(false);
        lblEditError.setText("Loading report...");

        SwingWorker<MyReportData, Void> worker
                = new SwingWorker<>() {

            private List<CatalogOption> categories;
            private List<CatalogOption> locations;

            @Override
            protected MyReportData doInBackground()
                    throws Exception {

                MyReportData data = controller.getReport(
                        reportId, currentUser.userId()
                );

                CatalogDAO dao = new CatalogDAO();

                categories = dao.getCategories();
                locations = dao.getLocations();

                return data;
            }

            @Override
            protected void done() {

                try {
                    report = get();

                    if (report == null) {
                        throw new IllegalStateException(
                                "Report not found."
                        );
                    }

                    cmbEditCategory.removeAllItems();
                    cmbEditLocation.removeAllItems();

                    for (CatalogOption c : categories) {
                        cmbEditCategory.addItem(c);
                    }

                    for (CatalogOption l : locations) {
                        cmbEditLocation.addItem(l);
                    }

                    selectOption(
                            cmbEditCategory,
                            report.categoryId()
                    );

                    selectOption(
                            cmbEditLocation,
                            report.locationId()
                    );

                    txtEditTitle.setText(report.title());

                    txtDescription.setText(
                            report.description()
                    );

                    txtEditDate.setText(
                            report.dateOccurred().toString()
                    );

                    lblEditType.setText(
                            "Report Type: " + report.itemType()
                    );

                    boolean lost
                            = "LOST".equals(report.itemType());

                    lblEditFeatures.setVisible(lost);
                    txtEditFeatures.setVisible(lost);

                    lblEditReward.setVisible(lost);
                    txtEditReward.setVisible(lost);

                    lblEditStorage.setVisible(!lost);
                    txtStorage.setVisible(!lost);

                    if (lost) {
                        txtEditFeatures.setText(
                                report.distinguishingFeatures()
                        );

                        txtEditReward.setText(
                                report.rewardOffered() == null
                                ? ""
                                : report.rewardOffered().toString()
                        );

                    } else {
                        txtStorage.setText(
                                report.storageLocation()
                        );
                    }

                    boolean editable
                            = report.status().equals("OPEN")
                            || report.status().equals("MATCHED");

                    btnSaveChanges.setEnabled(editable);

                    lblEditError.setText(
                            editable
                                    ? " "
                                    : "This report cannot be edited."
                    );

                } catch (Exception ex) {
                    ex.printStackTrace();

                    lblEditError.setText(
                            "Unable to load this report."
                    );
                }
            }
        };

        worker.execute();
    }

    private void selectOption(
            JComboBox combo,
            int selectedId) {

        for (int i = 0; i < combo.getItemCount(); i++) {

            Object item = combo.getItemAt(i);

            if (item instanceof CatalogOption option
                    && option.id() == selectedId) {

                combo.setSelectedIndex(i);
                return;
            }
        }

        combo.setSelectedIndex(-1);
    }
