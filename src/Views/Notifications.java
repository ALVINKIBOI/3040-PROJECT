    private NotificationData getSelectedNotification() {

        int row = tblNotifications.getSelectedRow();

        if (row < 0) {
            return null;
        }

        int modelRow
                = tblNotifications.convertRowIndexToModel(row);

        int notificationId = (Integer) tblNotifications.getModel()
                .getValueAt(modelRow, 0);

        for (NotificationData n : notifications) {

            if (n.notificationId() == notificationId) {
                return n;
            }
        }

        return null;
    }

    private void displaySelectedNotification() {

        NotificationData n
                = getSelectedNotification();

        if (n == null) {

            lblNotificationDetails.setText(
                    "Select a notification"
            );

            txtNotificationMessage.setText("");
            btnMarkAsRead.setEnabled(false);
            return;
        }

        lblNotificationDetails.setText(
                n.type() + " — " + n.createdAt()
        );

        txtNotificationMessage.setText(
                n.message()
        );

        txtNotificationMessage.setCaretPosition(0);

        btnMarkAsRead.setEnabled(
                !notificationBusy && !n.isRead()
        );
    }

    private void updateReadStatus(boolean markAll) {

        if (notificationBusy || currentUser == null) {
            return;
        }

        NotificationData selected
                = markAll ? null : getSelectedNotification();

        if (!markAll && selected == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a notification."
            );
            return;
        }

        notificationBusy = true;

        btnRefreshNotifications.setEnabled(false);
        btnMarkAsRead.setEnabled(false);
        btnMarkAllRead.setEnabled(false);

        lblNotificationError.setText(
                "Updating notifications..."
        );

        final int notificationId
                = selected == null ? 0 : selected.notificationId();

        SwingWorker<Void, Void> worker
                = new SwingWorker<>() {

            @Override
            protected Void doInBackground()
                    throws Exception {

                if (markAll) {

                    controller.markAllAsRead(
                            currentUser.userId()
                    );

                } else {

                    controller.markAsRead(
                            notificationId,
                            currentUser.userId()
                    );
                }

                return null;
            }

            @Override
            protected void done() {

                notificationBusy = false;

                try {
                    get();
                    loadNotifications();

                } catch (Exception ex) {

                    ex.printStackTrace();

                    btnRefreshNotifications.setEnabled(true);
                    btnMarkAllRead.setEnabled(true);

                    lblNotificationError.setText(
                            "Unable to update notification."
                    );

                    displaySelectedNotification();
                }
            }
        };

        worker.execute();
    }

