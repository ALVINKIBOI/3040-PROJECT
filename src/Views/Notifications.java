    private void configureNotificationsTable() {

        DefaultTableModel model
                = new DefaultTableModel(
                        new Object[][]{},
                        new String[]{
                            "ID",
                            "Type",
                            "Message",
                            "Date",
                            "Read Status"
                        }
                ) {
            @Override
            public boolean isCellEditable(
                    int row, int column) {
                return false;
            }
        };

        tblNotifications.setModel(model);
        tblNotifications.setRowHeight(36);
        tblNotifications.setAutoCreateRowSorter(true);

        tblNotifications.setSelectionMode(
                ListSelectionModel.SINGLE_SELECTION
        );

        tblNotifications.getSelectionModel()
                .addListSelectionListener(event -> {

                    if (!event.getValueIsAdjusting()) {
                        displaySelectedNotification();
                    }
                });
    }

    private void returnToDashboard() {

        if (notificationBusy) {
            JOptionPane.showMessageDialog(
                    this,
                    "A notification update is in progress."
            );
            return;
        }

        if (onReturnToDashboard != null) {
            onReturnToDashboard.run();
        }

        dispose();
    }

    private void loadNotifications() {

        if (currentUser == null || notificationBusy) {
            return;
        }

        notificationBusy = true;

        btnRefreshNotifications.setEnabled(false);
        btnMarkAsRead.setEnabled(false);
        btnMarkAllRead.setEnabled(false);

        lblNotificationError.setText(
                "Loading notifications..."
        );

        SwingWorker<List<NotificationData>, Void> worker
                = new SwingWorker<>() {

            @Override
            protected List<NotificationData>
                    doInBackground() throws Exception {

                return controller.getNotifications(
                        currentUser.userId()
                );
            }

            @Override
            protected void done() {

                notificationBusy = false;
                btnRefreshNotifications.setEnabled(true);
                btnMarkAllRead.setEnabled(true);

                try {
                    notifications = get();

                    DefaultTableModel model
                            = (DefaultTableModel) tblNotifications.getModel();

                    model.setRowCount(0);

                    int unread = 0;

                    for (NotificationData n : notifications) {

                        if (!n.isRead()) {
                            unread++;
                        }

                        model.addRow(new Object[]{
                            n.notificationId(),
                            n.type(),
                            n.message(),
                            n.createdAt(),
                            n.isRead() ? "Read" : "Unread"
                        });
                    }

                    lblUnreadCount.setText(
                            unread + " Unread"
                    );

                    lblNotificationDetails.setText(
                            "Select a notification"
                    );

                    txtNotificationMessage.setText("");
                    btnMarkAsRead.setEnabled(false);

                    lblNotificationError.setText(" ");

                } catch (Exception ex) {

                    ex.printStackTrace();

                    btnMarkAllRead.setEnabled(false);

                    lblNotificationError.setText(
                            "Unable to load notifications."
                    );
                }
            }
        };

        worker.execute();
    }

