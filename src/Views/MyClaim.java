    private void configureClaimsTable() {

        DefaultTableModel model
                = new DefaultTableModel(
                        new Object[][]{},
                        new String[]{
                            "Claim ID",
                            "Found Item",
                            "Date Submitted",
                            "Status"
                        }
                ) {
            @Override
            public boolean isCellEditable(
                    int row, int column) {
                return false;
            }
        };

        tblMyClaims.setModel(model);
        tblMyClaims.setRowHeight(36);
        tblMyClaims.setAutoCreateRowSorter(true);

        tblMyClaims.setSelectionMode(
                ListSelectionModel.SINGLE_SELECTION
        );

        tblMyClaims.getSelectionModel()
                .addListSelectionListener(event -> {

                    if (!event.getValueIsAdjusting()) {
                        displaySelectedClaim();
                    }
                });
    }

    private void displaySelectedClaim() {

        MyClaimData claim = getSelectedClaim();

        if (claim == null) {
            clearClaimDetails();
            return;
        }

        lblSelectedClaim.setText(
                "Claim #" + claim.claimId()
                + " — " + claim.itemTitle()
        );

        lblClaimStatus.setText(
                "Status: " + claim.status()
        );

        lblDecisionDate.setText(
                claim.reviewedAt() == null
                ? "Reviewed: Not yet reviewed"
                : "Reviewed: " + claim.reviewedAt()
        );

        txtClaimProof.setText(
                claim.proofDescription() == null
                ? ""
                : claim.proofDescription()
        );

        txtDecisionNote.setText(
                claim.decisionNote() == null
                ? "No decision has been recorded."
                : claim.decisionNote()
        );

        txtClaimProof.setCaretPosition(0);
        txtDecisionNote.setCaretPosition(0);
    }

    private void clearClaimDetails() {

        lblSelectedClaim.setText(
                "Select a claim"
        );

        lblClaimStatus.setText("Status: —");
        lblDecisionDate.setText("Reviewed: —");

        txtClaimProof.setText("");
        txtDecisionNote.setText("");

        txtClaimProof.setEditable(false);
        txtDecisionNote.setEditable(false);

        txtClaimProof.setLineWrap(true);
        txtClaimProof.setWrapStyleWord(true);

        txtDecisionNote.setLineWrap(true);
        txtDecisionNote.setWrapStyleWord(true);
    }

    private void loadMyClaims() {

        if (currentUser == null || loadingClaims) {
            return;
        }

        loadingClaims = true;

        btnRefresh.setEnabled(false);
        lblClaimsError.setText("Loading claims...");

        SwingWorker<List<MyClaimData>, Void> worker
                = new SwingWorker<>() {

            @Override
            protected List<MyClaimData> doInBackground()
                    throws Exception {

                return controller.getMyClaims(
                        currentUser.userId()
                );
            }

            @Override
            protected void done() {

                loadingClaims = false;
                btnRefresh.setEnabled(true);

                try {
                    myClaims = get();

                    DefaultTableModel model
                            = (DefaultTableModel) tblMyClaims.getModel();

                    model.setRowCount(0);

                    for (MyClaimData claim : myClaims) {

                        model.addRow(new Object[]{
                            claim.claimId(),
                            claim.itemTitle(),
                            claim.claimDate(),
                            claim.status()
                        });
                    }

                    lblClaimsCount.setText(
                            myClaims.size() + " claims found"
                    );

                    clearClaimDetails();
                    lblClaimsError.setText(" ");

                } catch (Exception ex) {

                    ex.printStackTrace();

                    lblClaimsError.setText(
                            "Unable to load your claims."
                    );
                }
            }
        };

        worker.execute();
    }

    private MyClaimData getSelectedClaim() {
        int row = tblMyClaims.getSelectedRow();

        if (row < 0) {
            return null;
        }

        int modelRow
                = tblMyClaims.convertRowIndexToModel(row);

        int claimId = (Integer) tblMyClaims.getModel()
                .getValueAt(modelRow, 0);

        for (MyClaimData claim : myClaims) {

            if (claim.claimId() == claimId) {
                return claim;
            }
        }

        return null;
    }

