    private void btnReportLostActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReportLostActionPerformed
        // TODO add your handling code here:

        if (currentUser == null
                || "ADMIN".equals(currentUser.role())) {
            return;
        }

        ReportLostItem lostForm
                = new ReportLostItem(
                        currentUser,
                        onReturnToDashboard
                );

        lostForm.setLocationRelativeTo(this);
        lostForm.setVisible(true);

        // Close only Browse Items.
        // Do not invoke the dashboard callback here.
        dispose();
    }//GEN-LAST:event_btnReportLostActionPerformed

