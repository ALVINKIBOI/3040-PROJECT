    private void loadPendingClaims() {

        if (currentUser == null || reviewInProgress) {
            return;
        }

        btnRefeshClaims.setEnabled(false);
        lblReviewError.setText("Loading pending claims...");

        SwingWorker<List<PendingClaimData>, Void> worker
                = new SwingWorker<>() {

            @Override
            protected List<PendingClaimData>
                    doInBackground() throws Exception {

                return controller.getPendingClaims(
                        currentUser.userId()
                );
            }

            @Override
            protected void done() {

                btnRefeshClaims.setEnabled(true);

                try {
                    pendingClaims = get();

                    DefaultTableModel model
                            = (DefaultTableModel) tblPendingClaims.getModel();

                    model.setRowCount(0);

                    for (PendingClaimData claim : pendingClaims) {

                        model.addRow(new Object[]{
                            claim.claimId(),
                            claim.itemTitle(),
                            claim.claimantName(),
                            claim.claimDate(),
                            claim.answerVerified()
                            ? "Matched"
                            : "Not Matched",
                            claim.status()
                        });
                    }

                    lblPendingCount.setText(
                            pendingClaims.size()
                            + " pending claims"
                    );

                    clearClaimDetails();
                    lblReviewError.setText(" ");

                } catch (Exception ex) {

                    ex.printStackTrace();

                    lblReviewError.setText(
                            "Unable to load pending claims."
                    );

                    JOptionPane.showMessageDialog(
                            ReviewClaim.this,
                            "Could not retrieve pending claims. "
                            + "Check your database connection "
                            + "and administrator permissions.",
                            "Database Error",
                            JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        };

        worker.execute();
    }

    private PendingClaimData getSelectedClaim() {

        int selectedRow
                = tblPendingClaims.getSelectedRow();

        if (selectedRow < 0) {
            return null;
        }

        int modelRow
                = tblPendingClaims.convertRowIndexToModel(
                        selectedRow
                );

        int claimId
                = (Integer) tblPendingClaims.getModel()
                        .getValueAt(modelRow, 0);

        for (PendingClaimData claim : pendingClaims) {

            if (claim.claimId() == claimId) {
                return claim;
            }
        }

        return null;
    }

    private void displaySelectedClaim() {

        PendingClaimData claim = getSelectedClaim();

        if (claim == null) {
            clearClaimDetails();
            return;
        }

        lblSelectedClaim.setText(
                "Claim #" + claim.claimId()
        );

        lblClaimantName.setText(
                "Claimant: " + claim.claimantName()
        );

        lblClaimantEmail.setText(
                "Email: " + claim.claimantEmail()
        );

        lblItemTitle.setText(
                "Item: " + claim.itemTitle()
        );

        lblVerificationResult.setText(
                claim.answerVerified()
                ? "Verification: Answer Matched"
                : "Verification: Answer Did Not Match"
        );

        lblVerificationResult.setForeground(
                claim.answerVerified()
                ? new java.awt.Color(22, 101, 52)
                : new java.awt.Color(185, 28, 28)
        );

        txtProofDescription.setText(
                claim.proofDescription() == null
                ? ""
                : claim.proofDescription()
        );

        txtProofDescription.setCaretPosition(0);

        boolean enabled = !reviewInProgress;

        btnApproveClaim.setEnabled(enabled);
        btnRejectClaim.setEnabled(enabled);
    }

    private void reviewSelectedClaim(boolean approve) {

        if (reviewInProgress || currentUser == null) {
            return;
        }

        PendingClaimData claim = getSelectedClaim();

        if (claim == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a pending claim first."
            );
            return;
        }

        String note = txtDecisionNote.getText().trim();

        if (!approve && note.isEmpty()) {

            lblReviewError.setText(
                    "Please enter a rejection reason."
            );

            txtDecisionNote.requestFocusInWindow();
            return;
        }

        String action = approve ? "approve" : "reject";

        int response = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to " + action
                + " claim #" + claim.claimId() + "?",
                "Confirm Claim Review",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (response != JOptionPane.YES_OPTION) {
            return;
        }

        reviewInProgress = true;

        btnApproveClaim.setEnabled(false);
        btnRejectClaim.setEnabled(false);
        btnRefeshClaims.setEnabled(false);

        lblReviewError.setText(
                "Processing claim..."
        );

        final int claimId = claim.claimId();

        SwingWorker<Void, Void> worker
                = new SwingWorker<>() {

            @Override
            protected Void doInBackground()
                    throws Exception {

                controller.reviewClaim(
                        currentUser.userId(),
                        claimId,
                        approve,
                        note
                );

                return null;
            }

            @Override
            protected void done() {

                reviewInProgress = false;
                btnRefeshClaims.setEnabled(true);

                try {
                    get();

                    String message = approve
                            ? "Claim approved successfully!\n"
                            + "Item status: RETURNED"
                            : "Claim rejected successfully!\n"
                            + "Item status: OPEN";

                    JOptionPane.showMessageDialog(
                            ReviewClaim.this,
                            message,
                            "Claim Review Complete",
                            JOptionPane.INFORMATION_MESSAGE
                    );

                    clearClaimDetails();
                    loadPendingClaims();

                } catch (Exception ex) {

                    Throwable cause = ex;

                    if (ex instanceof java.util.concurrent.ExecutionException
                            && ex.getCause() != null) {
                        cause = ex.getCause();
                    }

                    cause.printStackTrace();

                    lblReviewError.setText(
                            "Unable to process claim."
                    );

                    JOptionPane.showMessageDialog(
                            ReviewClaim.this,
                            cause.getMessage() == null
                            ? "Claim review failed."
                            : cause.getMessage(),
                            "Review Error",
                            JOptionPane.ERROR_MESSAGE
                    );

                    loadPendingClaims();
                }
            }
        };

        worker.execute();
    }

