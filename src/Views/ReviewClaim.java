    private void configureTable() {

        DefaultTableModel model
                = new DefaultTableModel(
                        new Object[][]{},
                        new String[]{
                            "Claim ID",
                            "Item",
                            "Claimant",
                            "Date Submitted",
                            "Answer Verified",
                            "Status"
                        }
                ) {
            @Override
            public boolean isCellEditable(
                    int row, int column) {
                return false;
            }
        };

        tblPendingClaims.setModel(model);

        tblPendingClaims.setRowHeight(36);
        tblPendingClaims.setShowGrid(false);
        tblPendingClaims.setAutoCreateRowSorter(true);

        tblPendingClaims.setSelectionMode(
                ListSelectionModel.SINGLE_SELECTION
        );

        tblPendingClaims.getTableHeader()
                .setReorderingAllowed(false);

        tblPendingClaims.getSelectionModel()
                .addListSelectionListener(event -> {

                    if (!event.getValueIsAdjusting()) {
                        displaySelectedClaim();
                    }
                });
    }

