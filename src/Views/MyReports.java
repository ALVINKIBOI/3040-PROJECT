    private void btnDeleteReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteReportActionPerformed
        // TODO add your handling code here:
        int itemId = getSelectedReportId();

        if (itemId < 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a report."
            );
            return;
        }

        int response = JOptionPane.showConfirmDialog(
                this,
                "Remove this report from active listings?\n"
                + "It will be soft-deleted, not "
                + "permanently erased.",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (response != JOptionPane.YES_OPTION) {
            return;
        }

        btnDeleteReport.setEnabled(false);

        SwingWorker<Void, Void> worker
                = new SwingWorker<>() {

            @Override
            protected Void doInBackground()
                    throws Exception {

                controller.deleteReport(
                        itemId, currentUser.userId()
                );

                return null;
            }

            @Override
            protected void done() {

                try {
                    get();

                    JOptionPane.showMessageDialog(
                            MyReports.this,
                            "Report removed successfully."
                    );

                    loadMyReports();

                } catch (Exception ex) {

                    Throwable cause
                            = ex instanceof java.util.concurrent.ExecutionException
                            && ex.getCause() != null
                            ? ex.getCause()
                            : ex;

                    JOptionPane.showMessageDialog(
                            MyReports.this,
                            cause.getMessage(),
                            "Delete Failed",
                            JOptionPane.ERROR_MESSAGE
                    );

                    loadMyReports();
                }
            }
        };

        worker.execute();
    }//GEN-LAST:event_btnDeleteReportActionPerformed

