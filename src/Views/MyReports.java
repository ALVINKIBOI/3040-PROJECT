    private void loadMyReports() {

        if (currentUser == null) {
            return;
        }

        String search
                = txtSearchReports.getText().trim();

        String type
                = (String) cmbReportType.getSelectedItem();

        if (type == null) {
            type = "ALL";
        }

        final String selectedType = type;

        btnSearchReports.setEnabled(false);
        btnRefreshReports.setEnabled(false);

        lblMyReportsError.setText("Loading reports...");

        SwingWorker<List<MyReportData>, Void> worker
                = new SwingWorker<>() {

            @Override
            protected List<MyReportData> doInBackground()
                    throws Exception {

                return controller.getMyReports(
                        currentUser.userId(),
                        search,
                        selectedType
                );
            }

            @Override
            protected void done() {

                btnSearchReports.setEnabled(true);
                btnRefreshReports.setEnabled(true);

                try {
                    reports = get();

                    DefaultTableModel model
                            = (DefaultTableModel) tblMyReports.getModel();

                    model.setRowCount(0);

                    for (MyReportData report : reports) {
                        model.addRow(new Object[]{
                            report.itemId(),
                            report.title(),
                            report.itemType(),
                            report.categoryName(),
                            report.locationName(),
                            report.dateOccurred(),
                            report.status()
                        });
                    }

                    lblMyReportsCount.setText(
                            reports.size() + " reports found"
                    );

                    lblMyReportsError.setText(" ");

                    lblSelectedReport.setText(
                            "Select a report"
                    );

                    btnEditReport.setEnabled(false);
                    btnDeleteReport.setEnabled(false);

                } catch (Exception ex) {
                    ex.printStackTrace();

                    lblMyReportsError.setText(
                            "Unable to load reports."
                    );
                }
            }
        };

        worker.execute();
    }

