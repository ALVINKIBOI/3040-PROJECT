    private int getSelectedReportId() {

        int selectedRow = tblMyReports.getSelectedRow();

        if (selectedRow < 0) {
            return -1;
        }

        int modelRow
                = tblMyReports.convertRowIndexToModel(
                        selectedRow
                );

        return (Integer) tblMyReports.getModel()
                .getValueAt(modelRow, 0);
    }

