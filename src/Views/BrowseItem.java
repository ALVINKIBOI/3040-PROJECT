    private boolean canClaimSelectedItem() {

        int row = tblItems.getSelectedRow();

        if (row < 0) {
            return false;
        }

        int modelRow
                = tblItems.convertRowIndexToModel(row);

        String type = String.valueOf(
                tblItems.getModel().getValueAt(modelRow, 2)
        );

        String status = String.valueOf(
                tblItems.getModel().getValueAt(modelRow, 6)
        );

        return "FOUND".equals(type)
                && ("OPEN".equals(status)
                || "MATCHED".equals(status))
                && currentUser != null
                && ("STUDENT".equals(currentUser.role())
                || "STAFF".equals(currentUser.role()));
    }

