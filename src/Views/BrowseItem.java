    private void showSelectedItem() {

        int selectedRow = tblItems.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select an item first.",
                    "No Item Selected",
                    JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        // Convert the visible row number because sorting
        // may have changed the table's row order.
        int modelRow
                = tblItems.convertRowIndexToModel(selectedRow);

        int itemId = (int) tblItems.getModel()
                .getValueAt(modelRow, 0);

        btnViewDetails.setEnabled(false);
        lblBrowseError.setText("Loading item details...");

        SwingWorker<ItemDetailsData, Void> worker
                = new SwingWorker<>() {

            @Override
            protected ItemDetailsData doInBackground()
                    throws Exception {

                return browseController.getDetails(itemId);
            }

            @Override
            protected void done() {

                btnViewDetails.setEnabled(true);

                try {
                    ItemDetailsData item = get();

                    if (item == null) {
                        lblBrowseError.setText(
                                "Item no longer available."
                        );
                        clearItemDetails();
                        return;
                    }

                    lblDetailTitle.setText("Item Title: " + item.title());
                    lblDetailType.setText(
                            "Type: " + item.itemType()
                    );
                    lblDetailCategory.setText(
                            "Category: " + item.category()
                    );
                    lblDetailLocation.setText(
                            "Location: " + item.location()
                    );
                    lblDetailDate.setText(
                            "Date: " + item.dateOccurred()
                    );
                    lblDetailStatus.setText(
                            "Status: " + item.status()
                    );

                    txtDetailDescription.setText(
                            "Item Description: " + item.description()
                    );

                    txtDetailDescription.setCaretPosition(0);

                    loadPhotoPreview(item.photoPath());

                    lblBrowseError.setText(" ");

                } catch (Exception ex) {

                    ex.printStackTrace();

                    lblBrowseError.setText(
                            "Unable to load item details."
                    );
                }
            }
        };

        worker.execute();
    }

    private void loadPhotoPreview(String photoPath) {

        lblDetailPhoto.setIcon(null);

        if (photoPath == null || photoPath.isBlank()) {
            lblDetailPhoto.setText("No photo available");
            return;
        }

        try {
            File file = new File(photoPath);

            if (!file.isFile()) {
                lblDetailPhoto.setText(
                        "Photo file not found"
                );
                return;
            }

            java.awt.image.BufferedImage original
                    = ImageIO.read(file);

            if (original == null) {
                lblDetailPhoto.setText(
                        "Unsupported image"
                );
                return;
            }

            int maxWidth = 220;
            int maxHeight = 150;

            double scale = Math.min(
                    (double) maxWidth / original.getWidth(),
                    (double) maxHeight / original.getHeight()
            );

            scale = Math.min(1.0, scale);

            int width = Math.max(
                    1,
                    (int) (original.getWidth() * scale)
            );

            int height = Math.max(
                    1,
                    (int) (original.getHeight() * scale)
            );

            Image scaled = original.getScaledInstance(
                    width,
                    height,
                    Image.SCALE_SMOOTH
            );

            lblDetailPhoto.setIcon(
                    new ImageIcon(scaled)
            );

            lblDetailPhoto.setText("");

        } catch (Exception ex) {

            lblDetailPhoto.setText(
                    "Unable to display photo"
            );

            ex.printStackTrace();
        }
    }

