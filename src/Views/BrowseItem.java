    private void loadFilters() {
        btnsearch.setEnabled(false);
        btnClearFilters.setEnabled(false);
        cmbFilterCategory.setEnabled(false);
        cmbFilterLocation.setEnabled(false);

        cmbFilterTypes.removeAllItems();
        cmbFilterTypes.addItem("All Types");
        cmbFilterTypes.addItem("LOST");
        cmbFilterTypes.addItem("FOUND");

        cmbFilterStatus.removeAllItems();
        cmbFilterStatus.addItem("All Statuses");
        cmbFilterStatus.addItem("OPEN");
        cmbFilterStatus.addItem("MATCHED");
        cmbFilterStatus.addItem("CLAIM_PENDING");
        cmbFilterStatus.addItem("RETURNED");
        cmbFilterStatus.addItem("ARCHIVED");
        btnsearch.setEnabled(true);
        btnClearFilters.setEnabled(true);

        SwingWorker<List<List<CatalogOption>>, Void> worker
                = new SwingWorker<>() {

            @Override
            protected List<List<CatalogOption>>
                    doInBackground() throws Exception {

                CatalogDAO dao = new CatalogDAO();

                return List.of(
                        dao.getCategories(),
                        dao.getLocations()
                );
            }

            @Override
            protected void done() {

                try {
                    var data = get();

                    cmbFilterCategory.removeAllItems();
                    cmbFilterLocation.removeAllItems();

                    cmbFilterCategory.addItem(
                            new CatalogOption(0, "All Categories")
                    );

                    cmbFilterLocation.addItem(
                            new CatalogOption(0, "All Locations")
                    );

                    for (CatalogOption option : data.get(0)) {
                        cmbFilterCategory.addItem(option);
                    }

                    for (CatalogOption option : data.get(1)) {
                        cmbFilterLocation.addItem(option);
                    }

                    cmbFilterCategory.setSelectedIndex(0);
                    cmbFilterLocation.setSelectedIndex(0);

                    cmbFilterCategory.setEnabled(true);
                    cmbFilterLocation.setEnabled(true);

                    lblBrowseError.setText(" ");

                    System.out.println(
                            "Categories loaded: "
                            + cmbFilterCategory.getItemCount()
                    );

                    System.out.println(
                            "Locations loaded: "
                            + cmbFilterLocation.getItemCount()
                    );

                    // IMPORTANT: Search after the filters finish loading
                    searchItems();

                } catch (Exception ex) {

                    lblBrowseError.setText(
                            "Unable to load filters."
                    );

                    ex.printStackTrace();
                }
            }
        };

        worker.execute();
    }

    private ItemSearchFilter buildFilter() {

        Object selectedCategory
                = cmbFilterCategory.getSelectedItem();

        Object selectedLocation
                = cmbFilterLocation.getSelectedItem();

        Integer categoryId = null;
        Integer locationId = null;

        // Safely extract Category ID
        if (selectedCategory instanceof CatalogOption category) {

            if (category.id() > 0) {
                categoryId = category.id();
            }
        }

        // Safely extract Location ID
        if (selectedLocation instanceof CatalogOption location) {

            if (location.id() > 0) {
                locationId = location.id();
            }
        }

        String type
                = (String) cmbFilterTypes.getSelectedItem();

        String status
                = (String) cmbFilterStatus.getSelectedItem();

        if (type == null || type.equals("All Types")) {
            type = null;
        }

        if (status == null || status.equals("All Statuses")) {
            status = null;
        }

        return new ItemSearchFilter(
                txtSearch.getText().trim(),
                categoryId,
                locationId,
                type,
                status
        );
    }

    private void searchItems() {

        if (currentUser == null) {
            return;
        }

        ItemSearchFilter filter = buildFilter();

        btnsearch.setEnabled(false);
        lblBrowseError.setText("Loading items...");

        SwingWorker<List<BrowseItemData>, Void> worker
                = new SwingWorker<>() {

            @Override
            protected List<BrowseItemData>
                    doInBackground() throws Exception {

                return browseController.search(filter);
            }

            @Override
            protected void done() {

                btnsearch.setEnabled(true);

                try {
                    List<BrowseItemData> items = get();

                    currentResults = items;

                    DefaultTableModel model
                            = (DefaultTableModel) tblItems.getModel();

                    model.setRowCount(0);

                    for (BrowseItemData item : items) {

                        model.addRow(new Object[]{
                            item.itemId(),
                            item.title(),
                            item.itemType(),
                            item.category(),
                            item.location(),
                            item.dateOccurred(),
                            item.status()
                        });
                    }

                    lblResultCount.setText(
                            items.size() + " items found"
                    );

                    lblBrowseError.setText(" ");

                    clearItemDetails();

                } catch (Exception ex) {

                    Throwable cause
                            = ex instanceof java.util.concurrent.ExecutionException
                            && ex.getCause() != null
                            ? ex.getCause()
                            : ex;

                    cause.printStackTrace();

                    lblBrowseError.setText(
                            "Unable to retrieve items."
                    );

                    JOptionPane.showMessageDialog(
                            BrowseItem.this,
                            "Could not load items from MySQL.",
                            "Database Error",
                            JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        };

        worker.execute();
    }

