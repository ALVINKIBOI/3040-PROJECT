    public ReportLostItem(
            AuthUser user,
            Runnable onComplete) {

        this();

        if (user == null || user.userId() <= 0) {
            throw new IllegalArgumentException(
                    "Login is required to report an item."
            );
        }

        this.currentUser = user;
        this.onComplete = onComplete;
        configureUserInterface();

        CatalogLoader.load(
                cmbLostCategory,
                cmbLostLocation,
                lblLostError
        );
    }

