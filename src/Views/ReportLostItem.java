    private void btnSubmitLostItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitLostItemActionPerformed
        // TODO add your handling code here:

        if (currentUser == null) {
            lblLostError.setText("Please log in first.");
            return;
        }

        try {
            CatalogOption category
                    = (CatalogOption) cmbLostCategory.getSelectedItem();

            CatalogOption location
                    = (CatalogOption) cmbLostLocation.getSelectedItem();

            if (category == null || location == null) {
                throw new IllegalArgumentException(
                        "Select a category and location."
                );
            }

            String rewardText = txtReward.getText().trim();

            BigDecimal reward = null;

            if (!rewardText.isEmpty()) {
                try {
                    reward = new BigDecimal(rewardText);

                    if (reward.compareTo(BigDecimal.ZERO) < 0) {
                        throw new IllegalArgumentException(
                                "Reward cannot be negative."
                        );
                    }

                } catch (NumberFormatException ex) {
                    lblLostError.setText(
                            "Enter a valid reward amount or leave it blank."
                    );
                    return;
                }
            }

            ItemReport data = new ItemReport(
                    "LOST",
                    currentUser.userId(),
                    category.id(),
                    location.id(),
                    txtLostTitle.getText().trim(),
                    txtDescription.getText().trim(),
                    LocalDate.parse(txtDateLost.getText().trim()),
                    selectedPhoto,
                    txtDistinguishingFeatures.getText().trim(),
                    reward,
                    null,
                    null
            );

            btnSubmitLostItem.setEnabled(false);
            lblLostError.setText("Saving report...");

            SwingWorker<Integer, Void> worker
                    = new SwingWorker<>() {

                @Override
                protected Integer doInBackground()
                        throws Exception {

                    int reportId = controller.submitReport(
                            data, null
                    );

                    try {
                        new Controllers.MatchingController()
                                .matchReport(reportId);

                    } catch (Exception matchError) {
                        matchError.printStackTrace();
                    }

                    return reportId;

                }

                @Override
                protected void done() {

                    btnSubmitLostItem.setEnabled(true);

                    try {
                        int id = get();

                        JOptionPane.showMessageDialog(
                                ReportLostItem.this,
                                "Lost item report saved!\n"
                                + "Report ID: " + id,
                                "Success",
                                JOptionPane.INFORMATION_MESSAGE
                        );

                        lblLostError.setText(" ");

                        if (onComplete != null) {
                            onComplete.run();
                        }

                    } catch (Exception ex) {

                        Throwable cause = ex;

                        if (ex instanceof java.util.concurrent.ExecutionException
                                && ex.getCause() != null) {
                            cause = ex.getCause();
                        }

                        lblLostError.setText(
                                cause instanceof IllegalArgumentException
                                        ? cause.getMessage()
                                        : "Unable to save report."
                        );

                        cause.printStackTrace();
                    }
                }
            };

            worker.execute();

        } catch (Exception ex) {
            lblLostError.setText(
                    "Check the date, reward, and required fields."
            );
        }
    }//GEN-LAST:event_btnSubmitLostItemActionPerformed

