    private void configureTable() {

        DefaultTableModel model
                = new DefaultTableModel(
                        new Object[][]{},
                        new String[]{
                            "Lost Item",
                            "Found Item",
                            "Category",
                            "Location",
                            "Date Found",
                            "Score",
                            "Status"
                        }
                ) {
            @Override
            public boolean isCellEditable(
                    int row, int column) {
                return false;
            }
        };

        tblSuggestedMatches.setModel(model);

        tblSuggestedMatches.setRowHeight(36);
        tblSuggestedMatches.setAutoCreateRowSorter(true);
        tblSuggestedMatches.setShowGrid(false);

        tblSuggestedMatches.setSelectionMode(
                ListSelectionModel.SINGLE_SELECTION
        );

        tblSuggestedMatches.getSelectionModel()
                .addListSelectionListener(event -> {

                    if (!event.getValueIsAdjusting()) {
                        displaySelectedMatch();
                    }
                });
    }

    private void returnToDashboard() {

        if (returning) {
            return;
        }

        if (loading) {
            JOptionPane.showMessageDialog(
                    this,
                    "Matching is currently in progress."
            );
            return;
        }

        returning = true;

        if (onReturnToDashboard != null) {
            onReturnToDashboard.run();
        }

        dispose();
    }

    private void loadSuggestedMatches() {

        if (currentUser == null || loading) {
            return;
        }

        loading = true;

        btnRefreshMatches.setEnabled(false);
        btnClaimMatchedItem.setEnabled(false);

        lblMatchError.setText(
                "Searching for potential matches..."
        );

        SwingWorker<List<MatchSuggestion>, Void> worker
                = new SwingWorker<>() {

            @Override
            protected List<MatchSuggestion>
                    doInBackground() throws Exception {

                controller.refreshMatchesForUser(
                        currentUser.userId()
                );

                return controller.getSuggestions(
                        currentUser.userId()
                );
            }

            @Override
            protected void done() {

                loading = false;
                btnRefreshMatches.setEnabled(true);

                try {
                    suggestions = get();

                    DefaultTableModel model
                            = (DefaultTableModel) tblSuggestedMatches.getModel();

                    model.setRowCount(0);

                    for (MatchSuggestion match : suggestions) {

                        model.addRow(new Object[]{
                            match.lostTitle(),
                            match.foundTitle(),
                            match.categoryName(),
                            match.locationName(),
                            match.foundDate(),
                            String.format(
                            java.util.Locale.ROOT,
                            "%.2f%%",
                            match.score()
                            ),
                            match.foundStatus()
                        });
                    }

                    lblMatchesCount.setText(
                            suggestions.size()
                            + " suggested matches"
                    );

                    lblSelectedMatch.setText(
                            "Select a match"
                    );

                    lblMatchScore.setText("Score: —");
                    btnClaimMatchedItem.setEnabled(false);
                    lblMatchError.setText(" ");

                } catch (Exception ex) {

                    ex.printStackTrace();

                    lblMatchError.setText(
                            "Unable to retrieve suggested matches."
                    );
                }
            }
        };

        worker.execute();
    }

    private MatchSuggestion getSelectedMatch() {

        int row
                = tblSuggestedMatches.getSelectedRow();

        if (row < 0 || suggestions.isEmpty()) {
            return null;
        }

        int modelRow
                = tblSuggestedMatches.convertRowIndexToModel(
                        row
                );

        if (modelRow < 0
                || modelRow >= suggestions.size()) {
            return null;
        }

        return suggestions.get(modelRow);
    }

    private void displaySelectedMatch() {

        MatchSuggestion match = getSelectedMatch();

        if (match == null) {
            lblSelectedMatch.setText(
                    "Select a match"
            );
            lblMatchScore.setText("Score: —");
            btnClaimMatchedItem.setEnabled(false);
            return;
        }

        lblSelectedMatch.setText(
                "Found Item: " + match.foundTitle()
        );

        lblMatchScore.setText(
                String.format(
                        java.util.Locale.ROOT,
                        "Matching Score: %.2f%%",
                        match.score()
                )
        );

        btnClaimMatchedItem.setEnabled(
                !loading
                && ("OPEN".equals(match.foundStatus())
                || "MATCHED".equals(match.foundStatus()))
        );
    }

