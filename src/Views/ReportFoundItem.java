    private void btnSubmitFoundItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitFoundItemActionPerformed
        // TODO add your handling code here:

        if (currentUser == null) {
            lblFoundError.setText("Please log in first.");
            return;
        }

        char[] answer
                = txtVerificationAnswer.getPassword();

        try {
            CatalogOption category
                    = (CatalogOption) cmbFoundCategory.getSelectedItem();

            CatalogOption location
                    = (CatalogOption) cmbFoundLocation.getSelectedItem();

            if (category == null || location == null) {
                throw new IllegalArgumentException(
                        "Select a category and location."
                );
            }

            ItemReport data = new ItemReport(
                    "FOUND",
                    currentUser.userId(),
                    category.id(),
                    location.id(),
                    txtFoundTitle.getText().trim(),
                    txtDescription.getText().trim(),
                    LocalDate.parse(txtDateFound.getText().trim()),
                    selectedPhoto,
                    null,
                    null,
                    txtStorgaeLocation.getText().trim(),
                    txtVerificationQuestion.getText().trim()
            );

            btnSubmitFoundItem.setEnabled(false);
            lblFoundError.setText("Saving report...");

            SwingWorker<Integer, Void> worker
                    = new SwingWorker<>() {

                @Override
                protected Integer doInBackground()
                        throws Exception {

                    int reportId = controller.submitReport(
                            data, answer
                    );

                    // Attempt matching after the report is saved.
                    try {
                        new Controllers.MatchingController()
                                .matchReport(reportId);

                    } catch (Exception matchError) {

                        // The submitted report is already saved.
                        // A matching failure must not falsely report
                        // that the original submission failed.
                        matchError.printStackTrace();
                    }

                    return reportId;

                }

                @Override
                protected void done() {

                    btnSubmitFoundItem.setEnabled(true);
                    txtVerificationAnswer.setText("");

                    try {
                        int id = get();

                        JOptionPane.showMessageDialog(
                                ReportFoundItem.this,
                                "Found item report saved!\n"
                                + "Report ID: " + id,
                                "Success",
                                JOptionPane.INFORMATION_MESSAGE
                        );

                        lblFoundError.setText(" ");

                        if (onComplete != null) {
                            onComplete.run();
                        }

                    } catch (Exception ex) {

                        Throwable cause = ex;

                        if (ex instanceof java.util.concurrent.ExecutionException
                                && ex.getCause() != null) {
                            cause = ex.getCause();
                        }

                        lblFoundError.setText(
                                cause instanceof IllegalArgumentException
                                        ? cause.getMessage()
                                        : "Unable to save report."
                        );

                        cause.printStackTrace();
                    }
                }
            };

            worker.execute();

        } catch (Exception ex) {

            java.util.Arrays.fill(answer, '\0');

            lblFoundError.setText(
                    "Check the date and required fields."
            );
        }
    }//GEN-LAST:event_btnSubmitFoundItemActionPerformed

